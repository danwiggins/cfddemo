"""Reproduce the wholly synthetic, Griffin-shaped parser fixture.

The column names and 15 bp coordinate grid follow Griffin's public TSV format.
Every numeric value below is generated by this script, not copied from a sample.
"""

from __future__ import annotations

from pathlib import Path


FIXTURE = Path(__file__).parent / "fixtures" / "griffin" / "Synthetic_demo.GC_corrected.coverage.tsv"
COORDINATES = tuple(range(-990, 976, 15))
METADATA = (
    "mean_reads_per_bp_in_normalization_window",
    "mean_reads_per_bp_in_saved_window",
    "mean_coverage",
    "central_coverage",
    "amplitude",
    "outlier_cutoff",
    "exclude_zero_mappability",
    "correction",
    "number_of_sites",
    "site_name",
    "smoothing",
    "CNA_normalization",
    "sample",
)


def synthetic_bytes() -> bytes:
    """Return deterministic artificial values in the upstream column layout."""

    assert len(COORDINATES) == 132
    coverage = [0.80 + ((index * 7) % 23) / 100 for index in range(len(COORDINATES))]
    central = [value for coordinate, value in zip(COORDINATES, coverage) if -30 <= coordinate <= 30]
    metadata = (
        "0.00100",
        "0.00150",
        f"{sum(coverage) / len(coverage):.5f}",
        f"{sum(central) / len(central):.5f}",
        "0.20000",
        "2.00000",
        "True",
        "GC_corrected",
        "1000",
        "CTCF_synthetic",
        "True",
        "False",
        "Synthetic_demo",
    )
    header = [*(str(coordinate) for coordinate in COORDINATES), *METADATA]
    row = [*(f"{value:.5f}" for value in coverage), *metadata]
    return ("\t".join(header) + "\n" + "\t".join(row) + "\n").encode("ascii")


if __name__ == "__main__":
    FIXTURE.write_bytes(synthetic_bytes())
